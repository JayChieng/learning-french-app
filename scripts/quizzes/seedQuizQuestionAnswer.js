export async function seedQuestionAnswerQuiz(lessonNumber) {
  const questions = questionSets[lessonNumber];

  if (!questions) {
    throw new Error(`No question-and-answer content is configured for Quiz ${lessonNumber}.`);
  }

  const lessonIds = [
    ...new Set([
      `lesson-${lessonNumber}`,
      ...sourceLessonNumbers.map((number) => `lesson-${number}`),
    ]),
  ];

  const questionsWithTranslations = questions.map(
    ([vocabularyId, question, answer, distractors]) => {
      const phrases = [question, answer, ...distractors];
      const missingTranslations = phrases.filter((phrase) => !phraseTranslations[phrase]);

      if (missingTranslations.length > 0) {
        throw new Error(
          `Quiz ${lessonNumber} has missing French translations: ${missingTranslations.join(", ")}`
        );
      }

      return {
        vocabularyId,
        prompt: "Complete B's reply.",
        dialogue: [
          { speaker: "A", text: question, translation: phraseTranslations[question] },
          { speaker: "B", text: "", blank: true },
        ],
        options: [
          { label: answer, isCorrect: true, translation: phraseTranslations[answer] },
          ...distractors.map((label) => ({
            label,
            isCorrect: false,
            translation: phraseTranslations[label],
          })),
        ],
      };
    }
  );

  await seedCustomQuiz({
    lessonIds,
    quizId: `quiz-${lessonNumber}`,
    title: `Quiz ${lessonNumber}: Lesson ${lessonNumber} Review`,
    description: `Practice distinct French question-and-answer conversations using question words and sentence patterns from Lessons ${lessonNumber} and earlier lessons.`,
    category: `Lesson ${lessonNumber} review`,
    dialogueMode: true,
    randomizeQuestionOrder: true,
    questions: questionsWithTranslations,
  });
}
